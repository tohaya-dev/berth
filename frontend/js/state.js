let _idleTimer = null;
let _idleTimerHandlersBound = false;
let _idleTimeoutMs = 0;

async function _initIdleTimeout() {
  try {
    const tok = State.token || localStorage.getItem('cynovela_token');
    if (!tok) return;
    const res = await fetch('/api/auth/session-config', {
      headers: { 'Authorization': 'Bearer ' + tok },
    });
    if (!res.ok) return;
    const cfg = await res.json();
    const minutes = cfg.idle_logout_minutes || 0;
    if (minutes > 0) {
      _startIdleTimer(minutes);
    }
  } catch (e) { /* ignore */ }
}

function _startIdleTimer(minutes) {
  _idleTimeoutMs = minutes * 60 * 1000;
  const reset = () => {
    if (_idleTimer) clearTimeout(_idleTimer);
    _idleTimer = setTimeout(() => {
      if (typeof window._showLockScreen === 'function') window._showLockScreen();
    }, _idleTimeoutMs);
  };
  if (!_idleTimerHandlersBound) {
    ['mousemove', 'keydown', 'click', 'touchstart'].forEach(evt => {
      document.addEventListener(evt, reset, { passive: true });
    });
    _idleTimerHandlersBound = true;
  }
  reset();
}

function _resetIdleTimer() {
  if (_idleTimer !== null) {
    clearTimeout(_idleTimer);
    if (_idleTimeoutMs > 0) {
      _idleTimer = setTimeout(() => {
        if (typeof window._showLockScreen === 'function') window._showLockScreen();
      }, _idleTimeoutMs);
    }
  }
}

