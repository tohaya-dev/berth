async function loadSession(sessionId) {
  State.sessionId = sessionId;
  closeP3Modal();
  // メッセージ履歴を取得して表示
  try {
    const msgs = await API.get(`/api/sessions/${sessionId}/messages`);
    const cm = $('chat-messages');
    if (!cm) return;
    cm.innerHTML = '';
    msgs.forEach(m => {
      const role = m.role === 'assistant' ? 'assistant' : 'user';
      // P4-1: 改行を <br> に変換（textContent ではなく innerHTML 経由なので必須）
      // P4-2: retrieval_json から citations/pipeline_detail を復元
      let citations = [];
      let pipelineDetail = null;
      if (m.retrieval_json) {
        try {
          const ret = typeof m.retrieval_json === 'string'
            ? JSON.parse(m.retrieval_json)
            : m.retrieval_json;
          citations = ret.citations || [];
          pipelineDetail = ret.pipeline_detail || null;
        } catch (e) {
          console.warn('retrieval_json parse error:', e);
        }
      }
      if (role === 'assistant') {
        const answerHtml = buildRagAnswerHtml(m.content, null);
        const citationsHtml = renderCitations(citations || []);
        const pipelineHtml = renderPipelineDetail(pipelineDetail);
        const feedbackHtml = renderFeedbackButtons(m.id);
        appendChatMessage('assistant', answerHtml + citationsHtml + pipelineHtml + feedbackHtml);
      } else {
        // user メッセージは改行を <br> に変換するだけ
        const safe = escapeHtml(m.content || '').replace(/\n/g, '<br>');
        appendChatMessage(role, safe);
      }
    });
    showToast(lj(`Session restored: ${msgs.length} messages`,`セッション復元: ${msgs.length}件のメッセージ`), 'info');
  } catch (e) {
    showToast(lj(`Session load failed: ${e.message}`,`セッション読込失敗: ${e.message}`), 'error');
  }
}

