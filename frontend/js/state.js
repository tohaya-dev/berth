function _applyCatalogSort(items) {
  const arr = items.slice();
  const sort = State.catalogSort || 'name_asc';
  const SENS = { restricted: 3, confidential: 2, internal: 1, public: 0 };
  arr.sort((a, b) => {
    switch (sort) {
      case 'name_desc':         return (b.name || '').localeCompare(a.name || '');
      case 'sensitivity_desc':  return (SENS[b.sensitivity] || 0) - (SENS[a.sensitivity] || 0);
      case 'accessed_desc':     return (b.last_accessed_at || '').localeCompare(a.last_accessed_at || '');
      case 'name_asc':
      default:                  return (a.name || '').localeCompare(b.name || '');
    }
  });
  return arr;
}

async function exportDataCatalog(format) {
  // catalog-export-authfix-20260711: 従来は window.location.href 直遷移で
  // Authorization ヘッダが付かず 401 だった。監査ログ CSV と同じ
  // fetch(Bearer)→blob→a.download 方式へ統一して認証付きダウンロードにする。
  try {
    const cat = State.catalogPager.category || '';
    const qs = new URLSearchParams({ format });
    if (cat) qs.set('category', cat);
    const url = `${API.base}/api/data-catalog/export?${qs}`;
    const headers = {};
    if (API.token) headers['Authorization'] = `Bearer ${API.token}`;
    const res = await fetch(url, { headers });
    if (!res.ok) {
      let detail = `HTTP ${res.status}`;
      try {
        const j = await res.json();
        detail = (j && (j.detail && j.detail.message)) || detail;
      } catch (_) { /* */ }
      throw new Error(detail);
    }
    const blob = await res.blob();
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    const fn = (res.headers.get('Content-Disposition') || '').match(/filename=([^;]+)/);
    a.download = fn ? fn[1].trim() : `cynovela_data_catalog.${format === 'json' ? 'json' : 'csv'}`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
    showToast(
      (CYNOVELA_LANG === 'ja') ? 'データカタログをエクスポートしました' : 'Data catalog exported',
      'success'
    );
  } catch (e) {
    showToast(lj('Export failed: ', 'エクスポート失敗: ') + (e && e.message || 'unknown'), 'error');
  }
}

