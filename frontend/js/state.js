function _applyWsFilterSort(items, filterArg, sortArg) {
  // fix-export-usable-container-20260717: 任意引数化（省略時は従来どおりグローバル読みで完全同一動作）
  const f = filterArg || State.wsFilter || {};
  let arr = items.slice();
  if (f.q) {
    arr = arr.filter(w => (w.name || '').toLowerCase().includes(f.q));
  }
  // sweep-fix-gen-wsfilter-20260711: BE(workspaces.py)が返す実フィールド名に整合。
  //   status/sort が別名参照(collection_count/published_count/chunk_count/last_scanned)で
  //   常に空振りだったのを published_collections / vectorized_chunks / last_scan_date に是正。
  if (f.status === 'published') {
    arr = arr.filter(w => (w.published_collections || 0) > 0);
  } else if (f.status === 'no_collection') {
    arr = arr.filter(w => !((w.published_collections || 0) > 0));
  }
  const sort = sortArg || State.wsSort || 'created_desc';
  arr.sort((a, b) => {
    switch (sort) {
      case 'created_asc':  return (a.created_at || '').localeCompare(b.created_at || '');
      case 'name_asc':     return (a.name || '').localeCompare(b.name || '');
      case 'name_desc':    return (b.name || '').localeCompare(a.name || '');
      case 'chunks_desc':  return (b.vectorized_chunks || 0) - (a.vectorized_chunks || 0);
      case 'scan_desc':    return (b.last_scan_date || '').localeCompare(a.last_scan_date || '');
      case 'created_desc':
      default:             return (b.created_at || '').localeCompare(a.created_at || '');
    }
  });
  return arr;
}

