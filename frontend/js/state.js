let _silentRefreshTimer = null;
function _scheduleTokenRefresh(token) {
  if (!token || !token.includes('.') || token.split('.').length !== 3) return;
  try {
    const payloadB64 = token.split('.')[1].replace(/-/g, '+').replace(/_/g, '/');
    const pad = payloadB64 + '=='.slice((payloadB64.length + 2) % 4);
    const payload = JSON.parse(atob(pad));
    const msUntilExpiry = payload.exp * 1000 - Date.now();
    const refreshAt = msUntilExpiry - 2 * 60 * 60 * 1000; // 残り2時間で更新
    if (_silentRefreshTimer) clearTimeout(_silentRefreshTimer);
    if (refreshAt > 0) {
      _silentRefreshTimer = setTimeout(_doSilentRefresh, refreshAt);
    }
  } catch (e) { /* demo-token 等は無視 */ }
}

async function _doSilentRefresh() {
  const rt = localStorage.getItem('cynovela_refresh_token');
  if (!rt) return;
  try {
    const res = await fetch('/api/auth/refresh', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ refresh_token: rt }),
    });
    if (res.ok) {
      const d = await res.json();
      localStorage.setItem('cynovela_token', d.access_token);
      State.token = d.access_token;
      API.token = d.access_token;
      _scheduleTokenRefresh(d.access_token);
    }
  } catch (e) { /* silent */ }
}

