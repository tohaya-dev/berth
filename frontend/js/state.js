// pathdisplay-20260706: パス表示の申告方式化（表示専用・保存値不変）。
// 管理者が Settings で申告した「取り込みフォルダの実際の場所」(settings key: ingest.host_path) が
// 非空のとき、/app/ingest 始まりのパスの【表示テキストのみ】接頭辞を申告値へ置き換える。
// POST/PUT に乗る値・DB 値・title 属性の元値は不変。未申告・/app/store/uploads 系・その他は素通し。
// settings は admin 限定 EP のため viewer は取得失敗＝'' フォールバック（現状表示のまま）。
let _ingestHostPathCache;  // undefined=未取得 / ''=未申告or取得不可 / 非空=申告値
// multi-ingest-roots-20260728: 複数根 (settings key: ingest.roots = JSON 文字列 [{name,host_path,label}])
// の表示写像キャッシュ。undefined=未取得 / []=なしor取得不可 / 配列=申告値。表示専用・保存値不変。
let _ingestRootsCache;
async function _loadIngestHostPath() {
  if (_ingestHostPathCache !== undefined) return _ingestHostPathCache;
  try {
    const s = await API.get('/api/settings');
    _ingestHostPathCache = (s && s['ingest.host_path']) ? String(s['ingest.host_path']).trim() : '';
    try {
      const roots = JSON.parse((s && s['ingest.roots']) || '[]');
      _ingestRootsCache = Array.isArray(roots) ? roots : [];
    } catch (e2) {
      _ingestRootsCache = [];
    }
  } catch (e) {
    _ingestHostPathCache = '';
    _ingestRootsCache = [];
  }
  return _ingestHostPathCache;
}
function _resetIngestHostPathCache() { _ingestHostPathCache = undefined; _ingestRootsCache = undefined; }
function _displaySourcePath(p) {
  if (!p) return '';
  const BOX = '/app/ingest';
  // multi-ingest-roots-20260728: 複数根写像を先に試す。/app/ingest/<name>(/...) → host_path + 残り。
  if (p.indexOf(BOX + '/') === 0) {
    const rest = p.slice(BOX.length + 1);
    const roots = _ingestRootsCache || [];
    for (const r of roots) {
      if (!r || !r.name || !r.host_path) continue;
      if (rest === r.name || rest.indexOf(r.name + '/') === 0) {
        return String(r.host_path).replace(/\/+$/, '') + rest.slice(r.name.length);
      }
    }
  }
  const base = _ingestHostPathCache || '';
  if (base && (p === BOX || p.indexOf(BOX + '/') === 0)) {
    return base.replace(/\/+$/, '') + p.slice(BOX.length);
  }
  // multi-ingest-roots-20260728: 複数根方式では /app/ingest 自体に単一のホスト側実体が無いため、
  // 内部パスをそのまま見せず「取り込み元」という表示文字列にする (表示専用)。
  if (p === BOX) return lj('Ingest sources', '取り込み元');
  return p;
}

