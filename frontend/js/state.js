const API = {
  base: window.location.origin,
  token: null,
  headers() {
    const h = { 'Content-Type': 'application/json' };
    if (this.token) h['Authorization'] = `Bearer ${this.token}`;
    return h;
  },
  // fix065-066 段 B: 401 セッション切れ時にログイン画面へ戻す。
  // _performLogout は logout API を叩いて再帰 401 を呼ぶため使わず、ここでローカル状態だけクリア。
  // item2 (2026-05-23): 未ログイン時の admin-only API 401 では発火させない (ログイン済セッション
  // 失効と区別)。token が一切無いなら "失効" ではなく、ログイン前のフォーム表示中の想定動作。
  _handleSessionExpired() {
    if (this._sessionExpiredHandled) return;
    // 未ログイン guard: in-memory token / localStorage token のいずれも無いなら何もしない
    let hadToken = !!this.token;
    if (!hadToken) {
      try { hadToken = !!localStorage.getItem('cynovela_token'); } catch (e) { /* ignore */ }
    }
    if (!hadToken) return;
    this._sessionExpiredHandled = true;
    this.token = null;
    try {
      if (typeof State !== 'undefined') { State.user = null; State.token = null; }
    } catch (e) { /* ignore */ }
    try {
      localStorage.removeItem('cynovela_token');
      localStorage.removeItem('cynovela_user');
    } catch (e) { /* ignore */ }
    // polling-401-fix (2026-09-21): セッション切れでも _performLogout と同じく alerts ポーリングを
    // 止める。止めないと token 無しのまま 60 秒ごとに /api/alerts を叩き続け、401 (auth_failed) が
    // 監査ログに毎分積もる。再ログイン時は _enterApp が startAlertPolling() で張り直す。
    try { if (typeof stopAlertPolling === 'function') stopAlertPolling(); } catch (e) { /* ignore */ }
    try {
      const shell = document.getElementById('app-shell');
      const modal = document.getElementById('login-modal');
      if (shell) shell.style.display = 'none';
      if (modal) modal.classList.add('active');
      if (typeof showLoginModal === 'function') showLoginModal();
    } catch (e) { /* ignore */ }
    // ログイン画面に「セッション切れ」を明示する (次のログイン試行で doLoginByPassword が消す)。
    try {
      const errEl = document.getElementById('login-error');
      if (errEl) {
        errEl.textContent = lj('Session expired. Please log in again.', 'セッションが切れました。再度ログインしてください。');
        errEl.style.display = '';
      }
    } catch (e) { /* ignore */ }
    setTimeout(() => { this._sessionExpiredHandled = false; }, 1500);
  },
  async get(path) {
    const res = await fetch(`${this.base}${path}`, { headers: this.headers() });
    if (res.status === 401) { this._handleSessionExpired(); const err = new Error(lj('Session expired. Please log in again.', 'セッションが切れました。再度ログインしてください。')); err.status = 401; throw err; }
    // polling-401-fix (2026-09-21): 定期ポーリング側が 403 (権限なし) を見分けて止まれるよう status を載せる。
    if (!res.ok) { const e = await res.json().catch(() => ({})); const err = new Error(e.detail || `HTTP ${res.status}`); err.status = res.status; throw err; }
    return res.json();
  },
  async post(path, body = {}, opts = {}) {
    const res = await fetch(`${this.base}${path}`, {
      method: 'POST', headers: this.headers(), body: JSON.stringify(body), signal: opts.signal
    });
    // allinone Phase D #2: ログイン失敗(401)は「セッション切れ」ではなくサーバの実メッセージ
    // (ユーザー名/パスワード誤り)を表示する。/api/auth/login は session-expired 処理から除外。
    if (res.status === 401 && !path.includes('/api/auth/login')) { this._handleSessionExpired(); const err = new Error(lj('Session expired. Please log in again.', 'セッションが切れました。再度ログインしてください。')); err.status = 401; throw err; }
    if (!res.ok) { const e = await res.json().catch(() => ({})); throw new Error(e.detail || `HTTP ${res.status}`); }
    return res.json();
  },
  async put(path, body = {}) {
    const res = await fetch(`${this.base}${path}`, {
      method: 'PUT', headers: this.headers(), body: JSON.stringify(body)
    });
    if (res.status === 401) { this._handleSessionExpired(); const err = new Error(lj('Session expired. Please log in again.', 'セッションが切れました。再度ログインしてください。')); err.status = 401; throw err; }
    if (!res.ok) { const e = await res.json().catch(() => ({})); throw new Error(e.detail || `HTTP ${res.status}`); }
    return res.json();
  },
  async patch(path, body = {}) {
    const res = await fetch(`${this.base}${path}`, {
      method: 'PATCH', headers: this.headers(), body: JSON.stringify(body)
    });
    if (res.status === 401) { this._handleSessionExpired(); const err = new Error(lj('Session expired. Please log in again.', 'セッションが切れました。再度ログインしてください。')); err.status = 401; throw err; }
    if (!res.ok) { const e = await res.json().catch(() => ({})); throw new Error(e.detail || `HTTP ${res.status}`); }
    return res.json();
  },
  async del(path) {
    const res = await fetch(`${this.base}${path}`, { method: 'DELETE', headers: this.headers() });
    if (res.status === 401) { this._handleSessionExpired(); const err = new Error(lj('Session expired. Please log in again.', 'セッションが切れました。再度ログインしてください。')); err.status = 401; throw err; }
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  },
};

