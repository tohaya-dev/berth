window._showLockScreen = function () {
  const overlay = document.getElementById('lock-overlay');
  if (!overlay) return;
  const uname = document.getElementById('lock-username');
  if (uname && State.user) {
    uname.textContent = State.user.display_name || State.user.username || '';
  }
  overlay.style.display = 'block';
  if (_idleTimer) clearTimeout(_idleTimer);
  setTimeout(() => {
    const inp = document.getElementById('lock-password');
    if (inp) inp.focus();
  }, 100);
};

window._unlockScreen = async function () {
  const inp = document.getElementById('lock-password');
  const pwd = inp ? inp.value : '';
  const errEl = document.getElementById('lock-error');
  if (errEl) errEl.textContent = '';
  if (!pwd) {
    if (errEl) errEl.textContent = 'パスワードを入力してください';
    return;
  }
  try {
    const tok = State.token || localStorage.getItem('cynovela_token');
    const res = await fetch('/api/auth/verify-password', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': 'Bearer ' + tok,
      },
      body: JSON.stringify({ password: pwd }),
    });
    if (res.ok) {
      document.getElementById('lock-overlay').style.display = 'none';
      if (inp) inp.value = '';
      _resetIdleTimer();
    } else {
      if (errEl) errEl.textContent = 'パスワードが違います';
      if (inp) inp.select();
    }
  } catch (e) {
    if (errEl) errEl.textContent = 'サーバーに接続できません';
  }
};

