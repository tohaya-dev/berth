function _applyColFilterSort(items) {
  let arr = items.slice();
  const f = State.colFilter || {};
  if (f.q) arr = arr.filter(c => (c.name || '').toLowerCase().includes(f.q));
  const sort = State.colSort || 'created_new';
  arr.sort((a, b) => {
    switch (sort) {
      case 'created_new': return (b.created_at || '').localeCompare(a.created_at || '');
      case 'created_old': return (a.created_at || '').localeCompare(b.created_at || '');
      case 'date_asc':    return (a.last_published_at || a.created_at || '').localeCompare(b.last_published_at || b.created_at || '');
      case 'date_desc':   return (b.last_published_at || b.created_at || '').localeCompare(a.last_published_at || a.created_at || '');
      case 'name_asc':    return (a.name || '').localeCompare(b.name || '');
      case 'chunks_desc': return (b.chunk_count || 0) - (a.chunk_count || 0);
      default:            return (b.created_at || '').localeCompare(a.created_at || '');
    }
  });
  return arr;
}

// fix-all-v2: Collection の公開状態バッジ (未Publish / 公開中 / 処理中 / 失敗)
function _colPublishStateBadge(col) {
  const cc = col.chunk_count || 0;
  const st = col.status || '';
  let label, bg, fg;
  if (st === 'publishing') { label = '⏳ 処理中'; bg = '#dbeafe'; fg = '#1e40af'; }
  else if (st === 'failed') { label = '❌ 失敗'; bg = '#fee2e2'; fg = '#991b1b'; }
  else if (cc > 0 && st === 'ready') { label = '✅ 公開中'; bg = '#dcfce7'; fg = '#166534'; }
  else { label = '📝 未Publish'; bg = '#f1f5f9'; fg = '#64748b'; }
  return `<span class="tag" style="background:${bg};color:${fg};">${label}</span>`;
}

// U-8 (DD-CYN-0020): Publish は「押した後に断る」のではなく「押す前に見せる」。
//   一覧を描いたあとで publish-diff を引き、前回の Publish から変更が無いコレクションは
//   再Publish ボタンを無効にし、無効にした理由をボタンの隣へ必ず出す (黙って押せなくしない)。
//   差分が取れなかったときは「変更が無い」とも「ある」とも言えないので、素通しで公開へ
//   進ませずに無効化し、失敗の中身を画面へ出す (フェイルクローズ)。
//   publish-diff は対象ファイル全件を sha256 する重い口なので、まだ一度も公開していない
//   コレクション (必ず has_changes=true) には引かない = data-pub-gate を付けない。
//   押した時点の再検査は publishCollection() と ui.js startPublishStream() が別に必ず行う。
async function _publishGateState(colId) {
  try {
    const diff = await API.get(`/api/collections/${colId}/publish-diff`);
    if (diff && diff.has_changes === false) {
      return { blocked: true, reason: lj(
        'No changes since the last publish. Update a document to publish again.',
        '前回の Publish から変更がありません。資料を更新すると再び押せます。') };
    }
    return { blocked: false, reason: '' };
  } catch (e) {
    return { blocked: true, reason: lj(
      `Could not check for changes, so Publish is blocked: ${e.message}`,
      `変更の有無を確認できないため Publish を止めています: ${e.message}`) };
  }
}

async function _applyPublishGate() {
  const btns = [...document.querySelectorAll('[data-pub-gate]')];
  if (!btns.length) return;
  // publish-diff は管理者限定の口。viewer には再Publish ボタン自体が出ないので引かない。
  const role = (State.demoRole || State.user?.role || '').toLowerCase();
  if (role !== 'admin') return;
  const ids = [...new Set(btns.map(b => b.dataset.pubGate))];
  const states = await Promise.all(ids.map(id => _publishGateState(id)));
  ids.forEach((id, i) => {
    const st = states[i];
    if (!st.blocked) return;   // 変更あり = 触らない (既に無効なボタンを有効化し直さない)
    document.querySelectorAll(`[data-pub-gate="${id}"]`).forEach(b => {
      b.disabled = true;
      b.title = st.reason;
    });
    document.querySelectorAll(`[data-pub-gate-reason="${id}"]`).forEach(el => {
      el.textContent = st.reason;
      el.style.display = '';
    });
  });
}

